// Bundles the Apps Script backend into a single file to paste into Google Apps Script:
//   node apps-script/build.mjs        ->  apps-script/Code.gs
import * as esbuild from "esbuild";
import path from "node:path";
import fs from "node:fs/promises";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = (f) => path.join(here, "src", f);

const result = await esbuild.build({
  entryPoints: [src("backend.mjs")],
  bundle: true, write: false, format: "iife", globalName: "ZP", platform: "neutral", target: "es2019",
  mainFields: ["module", "main"], legalComments: "none", logLevel: "warning",
  define: { "process.env": "globalThis.__ZP_ENV" },
  inject: [src("gas-shims.mjs")],
  plugins: [{
    name: "apps-script",
    setup(b) {
      b.onResolve({ filter: /^node:crypto$/ }, () => ({ path: src("gas-shims.mjs") }));
      b.onResolve({ filter: /^(node:fs\/promises|node:path|nodemailer|pdf-lib)$/ }, () => ({ path: src("stub.mjs") }));
      b.onResolve({ filter: /netlify[\\/]lib[\\/]store\.mjs$|^\.\/store\.mjs$/ }, (a) =>
        a.importer.includes(`${path.sep}netlify${path.sep}lib${path.sep}`) ? { path: src("store.mjs") } : undefined);
    },
  }],
});

const header = `/**
 * Zicco Plumbers website backend for Google Apps Script.
 * Generated by apps-script/build.mjs from apps-script/src and netlify/lib. Don't edit this file by hand.
 * Set-up steps: apps-script/README.md
 */

// >>> Paste your website's address between the quotes, e.g. "https://www.ziccoplumbersgp.co.za"
//     (links in emails point here). Leave it empty and the script learns it from the first visit.
var WEBSITE_URL = "";

// Script properties (Project Settings > Script properties) are read on every request.
globalThis.__ZP_ENV = (function () {
  var env = {};
  try { env = PropertiesService.getScriptProperties().getProperties(); } catch (e) { /* not available */ }
  if (WEBSITE_URL) env.SITE_URL = WEBSITE_URL.replace(/[/]+$/, "");
  return env;
})();
`;
const footer = `
// Entry points Google calls by name.
function doPost(e) { return ZP.doPost(e); }
function doGet(e) { return ZP.doGet(e); }
function setup() { return ZP.setup(); }
function dailyJob() { return ZP.dailyJob(); }
`;
await fs.writeFile(path.join(here, "Code.gs"), header + result.outputFiles[0].text + footer);
console.log("Wrote apps-script/Code.gs (" + Math.round(result.outputFiles[0].text.length / 1024) + " KB)");
